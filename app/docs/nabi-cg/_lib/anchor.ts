/**
 * 소제목 하나가 들어가고 **그 자리로 떨어지는 앵커**가 나온다. 색인을 굽는 쪽과 본문을 그리는
 * 쪽이 이 함수 하나를 나눠 써서, 검색 결과가 가리키는 `#`와 화면에 박히는 `id`가 어긋날 수 없다.
 *
 * **왜 한글 소제목을 그대로 안 쓰는가.** 02가 슬러그를 ASCII로 정한 잣대가 앵커에도 그대로
 * 걸린다 — 검색으로 딥 페이지에 떨어진 사람이 주소를 복사하는 순간 `#%EC%9E%90...`로 굳고,
 * 받아 적는 쪽에는 읽을 수도 부를 수도 없는 문자열이 남는다.
 *
 * **왜 순번(`#s1`·`#s2`)이 아닌가.** 순번은 섹션을 하나 끼워 넣는 순간 그 아래 전부가 밀려
 * 북마크가 조용히 다른 자리를 가리킨다. 해시는 소제목 글자에서만 나오므로 **순서가 바뀌어도
 * 안 움직이고, 소제목이 바뀔 때만 바뀐다** — 그때는 가리키던 자리가 실제로 없어진 때다.
 *
 * 대가는 기록해 둔다: 주소만 보고는 어느 절인지 알 수 없다.
 */
export function anchorOf(heading: string): string {
  // FNV-1a. 충돌은 같은 페이지 안에서만 문제가 되고 `buildDocs()`가 그때 빌드를 멈춘다
  let hash = 0x811c9dc5;
  for (let i = 0; i < heading.length; i++) {
    hash ^= heading.charCodeAt(i);
    hash = Math.imul(hash, 0x01000193) >>> 0;
  }
  return `s${hash.toString(36)}`;
}
